import { equal } from "../../helpers/I64";

import { ofNumber } from "./LSIntEnum";

function MWCMIsAnyCMThread(a) {
  return (
    equal(a, ofNumber(18)) ||
    equal(a, ofNumber(19)) ||
    equal(a, ofNumber(23)) ||
    equal(a, ofNumber(24)) ||
    equal(a, ofNumber(21)) ||
    equal(a, ofNumber(22))
  );
}

export default MWCMIsAnyCMThread;
