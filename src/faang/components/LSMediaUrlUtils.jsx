import { ofFloat, zero } from "../../helpers/I64";
import { getMillis } from "../../helpers/ServerTime";

function isTimestampExpired(timestamp) {
  if (gt(timestamp, zero)) {
    const currentTime = ofFloat(getMillis() / 1e3);
    return lt(timestamp, currentTime);
  }
  return false;
}

export { isTimestampExpired };
