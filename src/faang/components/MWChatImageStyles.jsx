import { getMWXBubbleCornerStyles } from "./MWXMessageBubbleCornerStyles";

// eslint-disable-next-line max-params
function calculateBorderStyles(connectBottom, connectTop, flatten, outgoing) {
  const align = outgoing === true ? "right" : "left";
  const imageStyles = getMWXBubbleCornerStyles({
    align,
    connectBottom,
    connectTop,
    flatten: flatten === true ? "bottom" : "none",
  });
  const insetShadowStyles = getMWXBubbleCornerStyles({
    connectBottom,
    connectTop,
    corners: "unset",
  });
  return { imageStyles, insetShadowStyles };
}

export { calculateBorderStyles };
